def _run_check(
    check_id: str, title: str, max_points: int, check: CheckFn, layout: Layout
) -> CheckResult:
    outcome = check(layout)
    return CheckResult(
        id=check_id,
        title=title,
        max_points=max_points,
        points=round(max_points * outcome.fraction),
        detail=outcome.detail,
        remediation=remediation(
            check_id,
            outcome.path,
            placeholder=outcome.placeholder,
            standalone=not layout.is_project,
        ),
        severity=SEVERITIES[check_id],
    )


def run_audit(repo_path: str | Path) -> AuditResult:
    """Inspect the repository at ``repo_path`` and return its scorecard. Read-only."""
    root = resolve_repo_root(repo_path)
    layout = resolve_layout(root)
    dimensions = tuple(
        DimensionResult(
            id=dimension_id,
            name=name,
            max_points=sum(max_points for _, _, max_points, _ in checks),
            checks=tuple(
                _run_check(check_id, title, max_points, check, layout)
                for check_id, title, max_points, check in checks
            ),
        )
        for dimension_id, name, checks in DIMENSION_SPECS
    )
    return AuditResult(
        repo_path=str(root), dimensions=dimensions, scaffold_path=str(layout.scaffold)
    )
