"""Static KAIDF-AMM scorecard: inspects a local K-AIDF repository and scores it out of 100.

Five dimensions of 20 points each. Each check returns a fraction between 0 and 1, and its
points are that fraction of the check's maximum, rounded to the nearest whole point.
Nothing is executed: the audit only reads files, and it never sends data anywhere.

Layout. The audited directory is the *root*; project-owned checks (credentials in tracked files,
CI workflows) run there. The *scaffold* is ``root/.kaidf`` when that directory exists (a project
set up with ``kob init``), else the root itself (a repository generated by kobkob-kaidf-generator
and audited directly). Scaffold-owned artifacts are looked up in the scaffold first and, for
repositories that keep some of them next to ``.kaidf/``, at the root as well. The Front Matter
v2 scan covers the scaffold's Markdown documents only: a project's own documentation next to
``.kaidf/`` is not a K-AIDF document. Details and remediations name the path that was actually
checked.

Placeholder rule. An artifact that exists but is a YAML or JSON mapping whose top-level key
``placeholder`` is true is the generator's unfilled placeholder: it scores 0 and its remediation
says to fill it in rather than to create it.
"""

from __future__ import annotations

import io
import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Literal

import yaml
from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.text import Text

from .repo import _parse_front_matter, resolve_repo_root

REQUIRED_FRONT_MATTER = ("id", "title", "document_class", "phase", "visibility", "status")
MAX_SCAN_BYTES = 1_000_000
SKIPPED_DIR_NAMES = {".git", ".venv", "node_modules", "__pycache__"}
TIERS = (("Platinum", 90), ("Gold", 75), ("Silver", 60))
UNRATED = "Non-Compliant / Unrated"
# Most to least severe. A check's severity says what a failure exposes:
#   critical: credentials or personal data exposed
#   high:     cost or human/CI control missing, so harm can happen unnoticed
#   medium:   governance artifact missing, so decisions cannot be audited
#   low:      structure or documentation, which is fixable without risk
SEVERITY_ORDER: tuple[str, ...] = ("critical", "high", "medium", "low")
Severity = Literal["critical", "high", "medium", "low"]

# Common credential shapes. A match is a finding, not proof: the report says what matched.
SECRET_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("OpenAI-style secret key", re.compile(r"\bsk-[A-Za-z0-9]{20,}")),
    ("OpenAI project key", re.compile(r"\bsk-proj-[A-Za-z0-9_-]{20,}")),
    ("GitHub personal access token", re.compile(r"\bghp_[A-Za-z0-9]{20,}")),
    ("GitHub fine-grained token", re.compile(r"\bgithub_pat_[A-Za-z0-9_]{20,}")),
    ("Slack token", re.compile(r"\bxox[bap]-[A-Za-z0-9-]{10,}")),
    ("Stripe live secret key", re.compile(r"\bsk_live_[A-Za-z0-9]{16,}")),
    ("AWS access key id", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Google API key", re.compile(r"\bAIza[0-9A-Za-z_\-]{35}")),
    ("private key block", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    (
        "hard-coded credential assignment",
        re.compile(
            r"(?i)\b(api[_-]?key|secret|token|password)\b\s*[:=]\s*[\"'][A-Za-z0-9_\-/+]{16,}[\"']"
        ),
    ),
)


@dataclass(frozen=True)
class CheckResult:
    id: str
    title: str
    max_points: int
    points: int
    detail: str
    remediation: str
    severity: Severity


@dataclass(frozen=True)
class DimensionResult:
    id: str
    name: str
    max_points: int
    checks: tuple[CheckResult, ...]

    @property
    def points(self) -> int:
        return sum(check.points for check in self.checks)


@dataclass(frozen=True)
class AuditResult:
    repo_path: str
    dimensions: tuple[DimensionResult, ...]
    # Where the scaffold-owned checks looked: ``<repo_path>/.kaidf`` or ``repo_path`` itself.
    scaffold_path: str = ""

    @property
    def score(self) -> int:
        return sum(dimension.points for dimension in self.dimensions)

    @property
    def max_score(self) -> int:
        return sum(dimension.max_points for dimension in self.dimensions)

    @property
    def tier(self) -> str:
        return classify_tier(self.score)

    @property
    def scaffold_label(self) -> str:
        """The scaffold location as the report shows it."""
        if not self.scaffold_path or self.scaffold_path == self.repo_path:
            return f"repository root (no {SCAFFOLD_DIRNAME}/)"
        return Path(self.scaffold_path).relative_to(self.repo_path).as_posix() + "/"

    def to_dict(self) -> dict[str, Any]:
        return {
            "repo_path": self.repo_path,
            "scaffold_path": self.scaffold_path,
            "score": self.score,
            "max_score": self.max_score,
            "tier": self.tier,
            "dimensions": [
                {
                    "id": dimension.id,
                    "name": dimension.name,
                    "points": dimension.points,
                    "max_points": dimension.max_points,
                    "checks": [
                        {
                            "id": check.id,
                            "title": check.title,
                            "points": check.points,
                            "max_points": check.max_points,
                            "detail": check.detail,
                            "remediation": check.remediation,
                            "severity": check.severity,
                        }
                        for check in dimension.checks
                    ],
                }
                for dimension in self.dimensions
            ],
        }


TIER_STYLES = {
    "Platinum": "bold green",
    "Gold": "bold green",
    "Silver": "bold yellow",
    UNRATED: "bold red",
}
STATUS_STYLES = {"Pass": "green", "Partial": "yellow", "Fail": "red"}
SEVERITY_STYLES = {"critical": "bold red", "high": "red", "medium": "yellow", "low": "cyan"}
BAR_WIDTH = 20


def _status(points: int, max_points: int) -> str:
    if points >= max_points:
        return "Pass"
    if points <= 0:
        return "Fail"
    return "Partial"


def _progress_bar(points: int, max_points: int) -> str:
    filled = round(BAR_WIDTH * points / max_points) if max_points else 0
    return "█" * filled + "░" * (BAR_WIDTH - filled)


def failed_checks(
    result: AuditResult, minimum_severity: str | None = None
) -> list[tuple[DimensionResult, CheckResult]]:
    """Checks that lost points, at or above ``minimum_severity`` (all severities when None)."""
    if minimum_severity is not None and minimum_severity not in SEVERITY_ORDER:
        raise ValueError(f"Unknown severity {minimum_severity!r}")
    limit = SEVERITY_ORDER.index(minimum_severity) if minimum_severity else len(SEVERITY_ORDER) - 1
    return [
        (dimension, check)
        for dimension in result.dimensions
        for check in dimension.checks
        if check.points < check.max_points and SEVERITY_ORDER.index(check.severity) <= limit
    ]


def has_critical_findings(result: AuditResult) -> bool:
    return any(check.severity == "critical" for _, check in failed_checks(result, "critical"))


def print_audit_report(
    result: AuditResult, console: Console, minimum_severity: str | None = None
) -> None:
    """Scorecard for a terminal: tier-coloured score, dimension table, remediation panel."""
    tier_style = TIER_STYLES[result.tier]
    score_line = Text()
    score_line.append(f"Score: {result.score}/{result.max_score}", style=tier_style)
    score_line.append("    ")
    score_line.append(f"Tier: {result.tier}", style=tier_style)
    console.print(
        Panel(
            score_line,
            title="KAIDF-AMM v1.0 - Audit Scorecard",
            subtitle=f"Scaffold: {result.scaffold_label}",
        )
    )

    dimensions = Table("Dimensão", "Pontuação", "Status", "Progresso")
    for dimension in result.dimensions:
        status = _status(dimension.points, dimension.max_points)
        dimensions.add_row(
            Text(dimension.name),
            f"{dimension.points}/{dimension.max_points}",
            Text(status, style=STATUS_STYLES[status]),
            Text(
                _progress_bar(dimension.points, dimension.max_points), style=STATUS_STYLES[status]
            ),
        )
    console.print(dimensions)

    failed = failed_checks(result, minimum_severity)
    if not failed:
        message = (
            "No failed checks."
            if minimum_severity is None
            else f"No findings at severity {minimum_severity} or above."
        )
        console.print(Panel(Text(message, style="green"), title="Remediações"))
        return
    body = Text()
    for index, (dimension, check) in enumerate(failed):
        if index:
            body.append("\n\n")
        body.append(f"[{check.severity.upper()}] ", style=SEVERITY_STYLES[check.severity])
        body.append(check.title, style="bold")
        body.append(f"  (-{check.max_points - check.points})", style="red")
        body.append(f"\n  Dimensão: {dimension.name}")
        body.append(f"\n  Achado: {check.detail}")
        body.append(f"\n  Ação: {check.remediation}")
    console.print(Panel(body, title="Remediações"))


def render_audit_report(result: AuditResult, minimum_severity: str | None = None) -> str:
    """The same scorecard as plain text, without colors (for the REPL transcript and tests)."""
    buffer = io.StringIO()
    console = Console(file=buffer, width=100, color_system=None, highlight=False)
    print_audit_report(result, console, minimum_severity)
    return buffer.getvalue()


def classify_tier(score: int) -> str:
    for name, minimum in TIERS:
        if score >= minimum:
            return name
    return UNRATED


# ---------------------------------------------------------------- file helpers


def _walk_files(root: Path) -> list[Path]:
    files: list[Path] = []
    for path in root.rglob("*"):
        relative = path.relative_to(root)
        if any(part in SKIPPED_DIR_NAMES or part.startswith("out") for part in relative.parts[:-1]):
            continue
        if path.is_file():
            files.append(path)
    return sorted(files)


def _tracked_files(root: Path) -> list[Path]:
    """Files git tracks, or every file on disk when the folder is not a git repository."""
    if not (root / ".git").exists():
        return _walk_files(root)
    listed = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"],
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8", errors="replace")
    return [root / name for name in listed.split("\0") if name]


def _read_text(path: Path) -> str | None:
    """Text content, or None for missing, oversized or binary files."""
    if not path.is_file() or path.stat().st_size > MAX_SCAN_BYTES:
        return None
    data = path.read_bytes()
    if b"\0" in data:
        return None
    return data.decode("utf-8", errors="replace")


def _load_yaml_mapping(path: Path) -> dict[str, Any] | None:
    text = _read_text(path)
    if text is None:
        return None
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError:
        return None
    return data if isinstance(data, dict) and data else None


def _load_json_mapping(path: Path) -> dict[str, Any] | None:
    text = _read_text(path)
    if text is None:
        return None
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def _load_mapping(path: Path) -> dict[str, Any] | None:
    """JSON for ``.json`` files, YAML otherwise."""
    return _load_json_mapping(path) if path.suffix == ".json" else _load_yaml_mapping(path)


def _non_empty_file(path: Path) -> bool:
    return path.is_file() and path.stat().st_size > 0


# ---------------------------------------------------------------- layout

SCAFFOLD_DIRNAME = ".kaidf"
PLACEHOLDER_KEY = "placeholder"


@dataclass(frozen=True)
class Layout:
    """Where the audit looks.

    ``root`` is the audited directory. ``scaffold`` is ``root/.kaidf`` when that directory
    exists, else ``root`` itself. Scaffold-owned artifacts are looked up in the scaffold first
    and then, in a project, at the root (repositories that keep some of them next to .kaidf/).
    """

    root: Path
    scaffold: Path

    @property
    def is_project(self) -> bool:
        """True when the scaffold is ``root/.kaidf``, as ``kob init`` lays it out."""
        return self.scaffold != self.root

    def candidates(self, relative: str) -> list[Path]:
        """Where a scaffold-owned artifact may be, in lookup order."""
        paths = [self.scaffold / relative]
        if self.is_project:
            paths.append(self.root / relative)
        return paths

    def locate(self, relative: str) -> Path:
        """The first existing candidate, or the scaffold location when none exists."""
        for path in self.candidates(relative):
            if path.exists():
                return path
        return self.scaffold / relative

    def glob(self, directory: str, pattern: str) -> list[Path]:
        """Matches in the scaffold's ``directory`` and, in a project, in the root's too."""
        found: list[Path] = []
        for base in self.candidates(directory):
            found.extend(sorted(base.glob(pattern)))
        return found

    def describe(self, path: Path) -> str:
        """``path`` relative to the audited root, as details and remediations show it."""
        return path.relative_to(self.root).as_posix()


def resolve_layout(root: Path) -> Layout:
    scaffold = root / SCAFFOLD_DIRNAME
    return Layout(root=root, scaffold=scaffold if scaffold.is_dir() else root)


def _is_placeholder(data: dict[str, Any] | None) -> bool:
    """The one placeholder rule: a mapping whose top-level ``placeholder`` key is true."""
    return data is not None and data.get(PLACEHOLDER_KEY) is True


# ---------------------------------------------------------------- checks
# Each check takes the layout and returns an Outcome: the fraction earned, the detail, the path
# it looked at (relative to the root, for the remediation) and whether that path is a placeholder.


@dataclass(frozen=True)
class Outcome:
    fraction: float
    detail: str
    path: str | None = None
    placeholder: bool = False


CheckFn = Callable[[Layout], Outcome]

# Scaffold-owned artifacts, relative to the scaffold.
MENTOR_STATE = "mentor-workflow.json"
SPECS_DIR = "specs"
PII_RULES = "policy/pii-masking-rules.yaml"
HITL_CONFIG = "policy/hitl-config.yaml"
BUDGET_POLICY = "policy/budget.yaml"
RISK_ASSESSMENT = "docs/20-ethical-model/risk-assessment.json"
EXPLICABILITY_SCHEMA = "docs/20-ethical-model/explicability-schema.json"
DATASET_AUDIT = "data/manifests/dataset-audit.yaml"
SKILLS_MANIFEST = "data/manifests/skills.yaml"


def _placeholder_outcome(shown: str) -> Outcome:
    return Outcome(0.0, f"{shown} is still the generator placeholder", shown, placeholder=True)


def _check_no_credentials(layout: Layout) -> Outcome:
    root = layout.root
    files = _tracked_files(root)
    if not files:
        # Nothing was inspected, so there is no evidence of absence.
        return Outcome(0.0, "no files to inspect")
    findings: list[str] = []
    not_scanned: list[str] = []
    for path in files:
        relative = path.relative_to(root).as_posix()
        name = path.name
        if name == ".env" or (
            name.startswith(".env.") and name not in {".env.example", ".env.sample"}
        ):
            findings.append(f"{relative}: environment file is tracked")
            continue
        if path.is_file() and path.stat().st_size > MAX_SCAN_BYTES:
            not_scanned.append(relative)
            continue
        text = _read_text(path)
        if text is None:
            continue
        for label, pattern in SECRET_PATTERNS:
            if pattern.search(text):
                findings.append(f"{relative}: {label}")
    # Oversized files are a blind spot, so the report names them even when nothing else fails.
    skipped = (
        f"not scanned, larger than {MAX_SCAN_BYTES} bytes: {', '.join(not_scanned[:5])}"
        + (" ..." if len(not_scanned) > 5 else "")
        if not_scanned
        else ""
    )
    if findings:
        detail = "; ".join(findings[:5]) + (" ..." if len(findings) > 5 else "")
        return Outcome(0.0, f"{detail}; {skipped}" if skipped else detail)
    if skipped:
        return Outcome(1.0, f"no credentials or environment files tracked; {skipped}")
    return Outcome(1.0, "no credentials or environment files tracked")


def _check_pii_rules(layout: Layout) -> Outcome:
    path = layout.locate(PII_RULES)
    shown = layout.describe(path)
    rules = _load_yaml_mapping(path)
    if rules is None:
        return Outcome(0.0, f"{shown} missing, empty or not a YAML mapping", shown)
    if _is_placeholder(rules):
        return _placeholder_outcome(shown)
    return Outcome(1.0, f"{shown} present and parseable", shown)


def _check_kaidf_scaffold(layout: Layout) -> Outcome:
    """A real scaffold has README.md and docs/. In a project, .kaidf/ itself is the marker; a
    standalone root must also carry the canonical doctrine package, docs/00-overview/, so that
    any repository with a README and a docs/ folder does not pass as a K-AIDF scaffold."""
    scaffold = layout.scaffold
    complete = (scaffold / "README.md").is_file() and (scaffold / "docs").is_dir()
    if not layout.is_project:
        complete = complete and (scaffold / "docs/00-overview").is_dir()
    if layout.is_project:
        where = f"{SCAFFOLD_DIRNAME}/"
        detail = (
            f"{where} has README.md and docs/"
            if complete
            else f"{where} is missing README.md or docs/"
        )
    elif complete:
        detail = (
            "repository root has README.md and docs/00-overview/ "
            f"(standalone scaffold, no {SCAFFOLD_DIRNAME}/)"
        )
    else:
        detail = (
            f"no {SCAFFOLD_DIRNAME}/, and the repository root is missing README.md or "
            "docs/00-overview/"
        )
    return Outcome(1.0 if complete else 0.0, detail)


def _check_mentor_state(layout: Layout) -> Outcome:
    path = layout.locate(MENTOR_STATE)
    shown = layout.describe(path)
    if _load_json_mapping(path) is not None:
        return Outcome(1.0, f"{shown} is a valid JSON object", shown)
    return Outcome(0.0, f"{shown} missing or not a valid JSON object", shown)


def _check_specs(layout: Layout) -> Outcome:
    specs = layout.glob(SPECS_DIR, "*.yaml") + layout.glob(SPECS_DIR, "*.yml")
    shown = layout.describe(layout.locate(SPECS_DIR)) + "/"
    if not specs:
        return Outcome(0.0, f"no YAML specs found under {shown}", shown)
    valid = sum(1 for spec in specs if _load_yaml_mapping(spec) is not None)
    return Outcome(
        valid / len(specs), f"{valid} of {len(specs)} YAML specs parse as mappings", shown
    )


def _check_front_matter(layout: Layout) -> Outcome:
    # Front Matter v2 is the contract of the generated documents, so only the scaffold is
    # scanned: a project's own Markdown next to .kaidf/ is not a K-AIDF document.
    documents = [path for path in _walk_files(layout.scaffold) if path.suffix == ".md"]
    if not documents:
        return Outcome(0.0, "no Markdown documents found")
    complete = 0
    for path in documents:
        text = _read_text(path)
        if text is None:
            continue
        front_matter, _ = _parse_front_matter(text)
        if all(front_matter.get(field) for field in REQUIRED_FRONT_MATTER):
            complete += 1
    return Outcome(
        complete / len(documents), f"{complete} of {len(documents)} Markdown documents complete"
    )


def _artifact_check(relative: str) -> CheckFn:
    """Present and non-empty, and not the generator placeholder."""

    def check(layout: Layout) -> Outcome:
        path = layout.locate(relative)
        shown = layout.describe(path)
        if not _non_empty_file(path):
            return Outcome(0.0, f"{shown} missing or empty", shown)
        if _is_placeholder(_load_mapping(path)):
            return _placeholder_outcome(shown)
        return Outcome(1.0, f"{shown} present", shown)

    return check


def _check_ci_workflows(layout: Layout) -> Outcome:
    workflows = _workflow_files(layout.root)
    if workflows:
        return Outcome(1.0, f"{len(workflows)} workflow file(s) in .github/workflows/")
    return Outcome(0.0, "no workflow files in .github/workflows/")


def _check_blocking_gates(layout: Layout) -> Outcome:
    root = layout.root
    workflows = _workflow_files(root)
    if not workflows:
        return Outcome(0.0, "no workflows, so no gate can block a merge")
    for path in workflows:
        text = _read_text(path) or ""
        if re.search(r"continue-on-error:\s*true", text):
            return Outcome(0.0, f"{path.relative_to(root).as_posix()} sets continue-on-error: true")
    return Outcome(1.0, "no workflow step is allowed to fail silently")


def _budget_policy(layout: Layout) -> tuple[dict[str, Any] | None, str]:
    """The budget policy mapping (None when missing or invalid) and the path checked."""
    path = layout.locate(BUDGET_POLICY)
    return _load_yaml_mapping(path), layout.describe(path)


def _check_budget_caps(layout: Layout) -> Outcome:
    policy, shown = _budget_policy(layout)
    if _is_placeholder(policy):
        return _placeholder_outcome(shown)
    policy = policy or {}
    max_tokens = policy.get("max_tokens")
    timeout = policy.get("request_timeout_seconds")
    valid = (
        isinstance(max_tokens, int)
        and not isinstance(max_tokens, bool)
        and max_tokens > 0
        and isinstance(timeout, (int, float))
        and not isinstance(timeout, bool)
        and timeout > 0
    )
    if valid:
        return Outcome(1.0, f"token cap and request timeout configured in {shown}", shown)
    return Outcome(0.0, f"{shown} lacks a positive max_tokens and request_timeout_seconds", shown)


def _check_local_fallback(layout: Layout) -> Outcome:
    policy, shown = _budget_policy(layout)
    if _is_placeholder(policy):
        return _placeholder_outcome(shown)
    if (policy or {}).get("local_fallback") is True:
        return Outcome(1.0, f"local fallback enabled in {shown}", shown)
    return Outcome(0.0, f"no local_fallback: true in {shown}", shown)


def _check_skills_manifest(layout: Layout) -> Outcome:
    """A valid manifest: a version, and a non-empty skills list whose entries each name an id,
    a command and their permissions. Ids must be unique."""
    path = layout.locate(SKILLS_MANIFEST)
    shown = layout.describe(path)
    manifest = _load_yaml_mapping(path)
    if manifest is None:
        return Outcome(0.0, f"{shown} missing, empty or not a YAML mapping", shown)
    skills = manifest.get("skills")
    if not isinstance(manifest.get("version"), str) or not isinstance(skills, list) or not skills:
        return Outcome(0.0, f"{shown} needs a version and a non-empty skills list", shown)
    ids: set[str] = set()
    for index, skill in enumerate(skills):
        if not isinstance(skill, dict):
            return Outcome(0.0, f"skills[{index}] is not a mapping", shown)
        skill_id = skill.get("id")
        if not isinstance(skill_id, str) or not skill_id.strip():
            return Outcome(0.0, f"skills[{index}] has no id", shown)
        if skill_id in ids:
            return Outcome(0.0, f"duplicate skill id {skill_id!r}", shown)
        ids.add(skill_id)
        if not isinstance(skill.get("command"), str) or not skill.get("command"):
            return Outcome(0.0, f"skill {skill_id!r} has no command", shown)
        if not isinstance(skill.get("permissions"), dict):
            return Outcome(0.0, f"skill {skill_id!r} has no permissions mapping", shown)
    return Outcome(1.0, f"{len(skills)} skill(s) registered in {shown}", shown)


def _workflow_files(root: Path) -> list[Path]:
    directory = root / ".github/workflows"
    if not directory.is_dir():
        return []
    return sorted(directory.glob("*.yml")) + sorted(directory.glob("*.yaml"))


