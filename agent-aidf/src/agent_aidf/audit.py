def remediation(
    check_id: str, path: str | None = None, *, placeholder: bool = False, standalone: bool = False
) -> str:
    """The action that recovers a check's points, naming the location that was checked.

    ``path`` is relative to the audited root. Without it the scaffold-relative location is
    named, which is the generic wording of the matrix. ``standalone`` selects the wording for
    a repository audited without .kaidf/, where a project-level action such as `kob mentor`
    cannot be followed.
    """
    if placeholder:
        template = PLACEHOLDER_REMEDIATION_TEMPLATES[check_id]
    elif standalone and check_id in STANDALONE_REMEDIATION_TEMPLATES:
        template = STANDALONE_REMEDIATION_TEMPLATES[check_id]
    else:
        template = REMEDIATION_TEMPLATES[check_id]
    return template.format(path=path or SCAFFOLD_PATHS.get(check_id, ""))


